    private static string RenderEnum(EnumBinding @enum)
    {
        var writer = new CodeWriter();

        if (@enum.IsFlags)
        {
            writer.Write("[Flags]");
        }

        writer.Write($$"""
            public enum {{@enum.ManagedName}} : {{GetManagedEnumUnderlyingTypeName(@enum)}}
            {
            """);

        foreach (var value in @enum.Values)
        {
            writer.Write($$"""
                {{value.ManagedName}} = {{value.ValueExpression}},
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static string RenderManagedProperty(FieldBinding field)
    {
        var writer = new CodeWriter();
        var propertyTypeName = GetManagedPublicReturnTypeName(field.Type);
        writer.Write($$"""
            public {{propertyTypeName}} {{field.ManagedName}}
            {
            get
            {
            """);

        if (field.Type.Kind == BindingTypeKind.Handle)
        {
            writer.Write($$"""
                return new {{field.Type.ManagedTypeName}}(__PInvoke_Get_{{field.ManagedName}}(Handle));
                """);
        }
        else
        {
            writer.Write($$"""
                return __PInvoke_Get_{{field.ManagedName}}(Handle);
                """);
        }

        writer.Write(
            """
            }
            """);

        if (!field.IsReadOnly)
        {
            var setterArgument = field.Type.Kind == BindingTypeKind.Handle
                ? "value is null ? 0 : value.Handle"
                : "value";

            writer.Write($$"""
                set
                {
                __PInvoke_Set_{{field.ManagedName}}(Handle, {{setterArgument}});
                }
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

