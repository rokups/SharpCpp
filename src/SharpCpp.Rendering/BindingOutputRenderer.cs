using SharpCpp.Model.Ast;
using SharpCpp.Model.Utilities;
using System.Text;

namespace SharpCpp.Rendering;

public static class BindingOutputRenderer
{
    public static GeneratedBindingSet Render(BindingCompilation compilation, string fileStem)
    {
        ArgumentNullException.ThrowIfNull(compilation);
        ArgumentException.ThrowIfNullOrWhiteSpace(fileStem);

        var files = new[]
        {
            new GeneratedBindingFile($"{fileStem}.Bindings.g.cs", RenderManagedBindings(compilation)),
            new GeneratedBindingFile($"{fileStem}.Bindings.Aliases.g.cs", RenderAliasBindings()),
            new GeneratedBindingFile($"{fileStem}.Bindings.g.cpp", RenderNativeBindings(compilation))
        };

        return new GeneratedBindingSet(files);
    }

    private static string RenderManagedBindings(BindingCompilation compilation)
    {
        var writer = new CodeWriter();
        var records = compilation.Records.OrderBy(static record => record.ManagedName, StringComparer.Ordinal).ToArray();
        var functions = compilation.Functions.OrderBy(static function => function.ManagedName, StringComparer.Ordinal).ToArray();

        writer.Write(
            $$"""
            // <auto-generated />
            using System.Runtime.InteropServices;

            namespace {{compilation.ManagedNamespace}};
            """);

        foreach (var record in records)
        {
            writer.WriteLine();
            writer.Write(RenderRecord(compilation, record));
        }

        foreach (var @enum in compilation.Enums.OrderBy(static item => item.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write(RenderEnum(@enum));
        }

        writer.WriteLine();
        writer.Write(
            $$"""
            public static partial class {{compilation.ManagedClassName}}
            {
            """);

        foreach (var function in functions.Where(static function => function.Parent is not RecordBinding && !function.IsConstructor))
        {
            writer.WriteLine();
            writer.Write(RenderManagedWrapperMethod(function));
            writer.WriteLine();
            writer.Write(RenderManagedImportDeclaration(compilation, function));
        }

        writer.WriteLine();
        writer.Write(
            """
            }
            """);

        return writer.ToString();
    }

    private static string RenderManagedWrapperMethod(FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            function.Parameters.Select(RenderManagedPublicParameter));
        var invocationPlan = BuildManagedInvocationPlan(function.Parameters);
        var invokeArguments = string.Join(", ", invocationPlan.Arguments);
        var returnTypeName = GetManagedPublicReturnTypeName(function.ReturnType);
        var importMethodName = GetManagedImportMethodName(function);

        writer.Write($$"""
            public static {{returnTypeName}} {{function.ManagedName}}({{parameterList}})
            {
            """);

        foreach (var statement in invocationPlan.PreCallStatements)
        {
            writer.Write(statement);
        }

        if (function.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
        {
            writer.Write($$"""
                {{importMethodName}}({{invokeArguments}});
                """);

            foreach (var statement in invocationPlan.PostCallStatements)
            {
                writer.Write(statement);
            }
        }
        else if (function.ReturnType.Kind == BindingTypeKind.Handle)
        {
            writer.Write($$"""
                var __result = {{importMethodName}}({{invokeArguments}});
                """);

            foreach (var statement in invocationPlan.PostCallStatements)
            {
                writer.Write(statement);
            }

            writer.Write($$"""
                return new {{function.ReturnType.ManagedTypeName}}(__result{{(function.ReturnsOwnedHandle ? ", true" : string.Empty)}});
                """);
        }
        else
        {
            writer.Write($$"""
                var __result = {{importMethodName}}({{invokeArguments}});
                """);

            foreach (var statement in invocationPlan.PostCallStatements)
            {
                writer.Write(statement);
            }

            writer.Write(
                """
                return __result;
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static string RenderManagedImportDeclaration(BindingCompilation compilation, FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            function.Parameters.Select(RenderManagedParameter));
        var returnTypeName = GetManagedImportTypeName(function.ReturnType);
        var returnAttribute = GetManagedReturnAttribute(function.ReturnType);
        var importMethodName = GetManagedImportMethodName(function);

        writer.Write(
            $$"""
            [LibraryImport("{{compilation.NativeLibraryName}}", EntryPoint = "{{function.EntryPointName}}")]
            {{returnAttribute}}
            private static partial {{returnTypeName}} {{importMethodName}}({{parameterList}});
            """);
        return writer.ToString();
    }

    private static string RenderAliasBindings()
    {
        return "// <auto-generated />\n// No alias glue is required for this bootstrap pipeline.\n";
    }

    private static string RenderRecord(BindingCompilation compilation, RecordBinding record)
    {
        var writer = new CodeWriter();
        var baseClause = string.IsNullOrWhiteSpace(record.ManagedBaseTypeName)
            ? " : global::System.IDisposable"
            : $" : {record.ManagedBaseTypeName}";
        writer.Write(
            $$"""
            public partial class {{record.ManagedName}}{{baseClause}}
            {
            internal {{record.ManagedName}}(nint handle, bool ownsHandle = false)
            {{(string.IsNullOrWhiteSpace(record.ManagedBaseTypeName) ? string.Empty : "    : base(handle, ownsHandle)")}}
            {
            {{(string.IsNullOrWhiteSpace(record.ManagedBaseTypeName) ? "Handle = handle;" : string.Empty)}}
            {{(string.IsNullOrWhiteSpace(record.ManagedBaseTypeName) ? "OwnsHandle = ownsHandle;" : string.Empty)}}
            }

            {{(string.IsNullOrWhiteSpace(record.ManagedBaseTypeName) ? "public nint Handle { get; private set; }" : string.Empty)}}
            {{(string.IsNullOrWhiteSpace(record.ManagedBaseTypeName) ? "public bool OwnsHandle { get; }" : string.Empty)}}
            {{(string.IsNullOrWhiteSpace(record.ManagedBaseTypeName) ? "public bool IsNull => Handle == 0;" : string.Empty)}}
            """);

        if (record.Members.OfType<FunctionBinding>().Any(static function => function.OperatorToken is "==" or "!="))
        {
            writer.WriteLine();
            writer.Write($$"""
                public override bool Equals(object obj)
                {
                return obj is {{record.ManagedName}} other && this == other;
                }

                public override int GetHashCode()
                {
                return Handle.GetHashCode();
                }
                """);
        }

        writer.WriteLine();
        writer.Write(RenderManagedDispose(record));
        writer.WriteLine();
        writer.Write(RenderManagedDeleteImportDeclaration(compilation, record));

        var accessorProperties = CollectAccessorProperties(record);
        var accessorMethodIds = accessorProperties
            .SelectMany(static property => new[] { property.Getter?.SymbolId, property.Setter?.SymbolId })
            .Where(static symbolId => !string.IsNullOrWhiteSpace(symbolId))
            .ToHashSet(StringComparer.Ordinal);

        foreach (var constructor in record.Members.OfType<FunctionBinding>().Where(static function => function.IsConstructor).OrderBy(static function => function.Parameters.Count))
        {
            writer.WriteLine();
            writer.Write(RenderManagedConstructor(constructor));
            writer.WriteLine();
            writer.Write(RenderManagedConstructorImportDeclaration(compilation, constructor));
        }

        foreach (var property in accessorProperties.OrderBy(static property => property.PropertyName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write(RenderManagedAccessorProperty(property));

            if (property.Getter is not null)
            {
                writer.WriteLine();
                writer.Write(RenderManagedInstanceImportDeclaration(compilation, property.Getter));
            }

            if (property.Setter is not null)
            {
                writer.WriteLine();
                writer.Write(RenderManagedInstanceImportDeclaration(compilation, property.Setter));
            }
        }

        foreach (var method in record.Members.OfType<FunctionBinding>().Where(function => !function.IsConstructor && !function.IsStatic && !function.IsConversionOperator && function.OperatorToken is null && !accessorMethodIds.Contains(function.SymbolId)).OrderBy(static method => method.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write(RenderManagedInstanceMethod(compilation, record, method));
            writer.WriteLine();
            writer.Write(RenderManagedInstanceImportDeclaration(compilation, method));
        }

        foreach (var method in record.Members.OfType<FunctionBinding>().Where(static function => function.IsStatic && !function.IsConversionOperator && function.OperatorToken is null).OrderBy(static method => method.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write(RenderManagedStaticMethod(method));
            writer.WriteLine();
            writer.Write(RenderManagedStaticImportDeclaration(compilation, method));
        }

        foreach (var method in record.Members.OfType<FunctionBinding>().Where(static function => function.IsConversionOperator || function.OperatorToken is not null).OrderBy(static method => method.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write(RenderManagedOperator(record, method));
            writer.WriteLine();
            writer.Write(RenderManagedOperatorImportDeclaration(compilation, method));
        }

        foreach (var field in record.Members.OfType<FieldBinding>().OrderBy(static field => field.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write(RenderManagedProperty(field));
            writer.WriteLine();
            writer.Write(RenderManagedFieldGetterImportDeclaration(compilation, field));

            if (!field.IsReadOnly)
            {
                writer.WriteLine();
                writer.Write(RenderManagedFieldSetterImportDeclaration(compilation, field));
            }
        }

        writer.WriteLine();
        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static string RenderManagedInstanceMethod(BindingCompilation compilation, RecordBinding record, FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            function.Parameters.Select(RenderManagedPublicParameter));
        var invocationPlan = BuildManagedInvocationPlan(function.Parameters);
        var invokeArguments = string.Join(", ", new[] { "Handle" }.Concat(invocationPlan.Arguments));
        var returnTypeName = GetManagedPublicReturnTypeName(function.ReturnType);
        var importMethodName = GetManagedImportMethodName(function);
        var memberModifier = ShouldUseNewModifier(compilation, record, function.ManagedName) ? "new " : string.Empty;

        writer.Write($$"""
            public {{memberModifier}}{{returnTypeName}} {{function.ManagedName}}({{parameterList}})
            {
            """);

        foreach (var statement in invocationPlan.PreCallStatements)
        {
            writer.Write(statement);
        }

        if (function.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
        {
            writer.Write($$"""
                {{importMethodName}}({{invokeArguments}});
                """);

            foreach (var statement in invocationPlan.PostCallStatements)
            {
                writer.Write(statement);
            }
        }
        else if (function.ReturnType.Kind == BindingTypeKind.Handle)
        {
            writer.Write($$"""
                var __result = {{importMethodName}}({{invokeArguments}});
                """);

            foreach (var statement in invocationPlan.PostCallStatements)
            {
                writer.Write(statement);
            }

            writer.Write($$"""
                return new {{function.ReturnType.ManagedTypeName}}(__result{{(function.ReturnsOwnedHandle ? ", true" : string.Empty)}});
                """);
        }
        else
        {
            writer.Write($$"""
                var __result = {{importMethodName}}({{invokeArguments}});
                """);

            foreach (var statement in invocationPlan.PostCallStatements)
            {
                writer.Write(statement);
            }

            writer.Write(
                """
                return __result;
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static bool ShouldUseNewModifier(BindingCompilation compilation, RecordBinding record, string managedName)
    {
        if (string.IsNullOrWhiteSpace(record.ManagedBaseTypeName))
        {
            return false;
        }

        var baseRecord = compilation.Records.FirstOrDefault(candidate => string.Equals(candidate.ManagedName, record.ManagedBaseTypeName, StringComparison.Ordinal));
        return baseRecord is not null &&
               baseRecord.Members.OfType<FunctionBinding>().Any(candidate => string.Equals(candidate.ManagedName, managedName, StringComparison.Ordinal));
    }

    private static string RenderManagedDispose(RecordBinding record)
    {
        if (string.IsNullOrWhiteSpace(record.ManagedBaseTypeName))
        {
            return """
                public void Dispose()
                {
                if (Handle == 0)
                {
                return;
                }

                var handle = Handle;
                Handle = 0;

                if (OwnsHandle)
                {
                DisposeCore(handle);
                }

                global::System.GC.SuppressFinalize(this);
                }

                protected virtual void DisposeCore(nint handle)
                {
                __PInvoke_Delete(handle);
                }
                """;
        }

        return """
            protected override void DisposeCore(nint handle)
            {
            __PInvoke_Delete(handle);
            }
            """;
    }

    private static string RenderManagedDeleteImportDeclaration(BindingCompilation compilation, RecordBinding record)
    {
        return $$"""
            [LibraryImport("{{compilation.NativeLibraryName}}", EntryPoint = "sharpcpp_e2e_{{record.NativeName}}_delete")]
            private static partial void __PInvoke_Delete(nint self);
            """;
    }

    private static string RenderManagedAccessorProperty(AccessorProperty property)
    {
        var writer = new CodeWriter();
        var type = property.Getter?.ReturnType ?? property.Setter!.Parameters[0].Type;
        var propertyTypeName = GetManagedPublicReturnTypeName(type);

        writer.Write($$"""
            public {{propertyTypeName}} {{property.PropertyName}}
            {
            """);

        if (property.Getter is not null)
        {
            if (property.Getter.ReturnType.Kind == BindingTypeKind.Handle)
            {
                writer.Write($$"""
                    get
                    {
                    return new {{property.Getter.ReturnType.ManagedTypeName}}({{GetManagedImportMethodName(property.Getter)}}(Handle));
                    }
                    """);
            }
            else
            {
                writer.Write($$"""
                    get
                    {
                    return {{GetManagedImportMethodName(property.Getter)}}(Handle);
                    }
                    """);
            }
        }

        if (property.Setter is not null)
        {
            var setterArgument = property.Setter.Parameters[0].Type.Kind == BindingTypeKind.Handle
                ? "value is null ? 0 : value.Handle"
                : "value";
            writer.Write($$"""
                set
                {
                {{GetManagedImportMethodName(property.Setter)}}(Handle, {{setterArgument}});
                }
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static IReadOnlyList<AccessorProperty> CollectAccessorProperties(RecordBinding record)
    {
        var getters = new Dictionary<string, FunctionBinding>(StringComparer.Ordinal);
        var setters = new Dictionary<string, FunctionBinding>(StringComparer.Ordinal);

        foreach (var method in record.Members.OfType<FunctionBinding>())
        {
            if (!method.TryGetMetadata<AccessorPropertyAnnotation>(MetadataKeys.AccessorProperty, out var accessor) || accessor is null)
            {
                continue;
            }

            if (accessor.Kind == AccessorPropertyKind.Getter)
            {
                getters[accessor.PropertyName] = method;
            }
            else
            {
                setters[accessor.PropertyName] = method;
            }
        }

        return getters.Keys
            .Concat(setters.Keys)
            .Distinct(StringComparer.Ordinal)
            .Select(propertyName => new AccessorProperty(
                propertyName,
                getters.TryGetValue(propertyName, out var getter) ? getter : null,
                setters.TryGetValue(propertyName, out var setter) ? setter : null))
            .ToArray();
    }

    private static string RenderManagedConstructor(FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            function.Parameters.Select(RenderManagedPublicParameter));
        var invokeArguments = string.Join(", ", function.Parameters.Select(RenderManagedInvocationArgument));
        var constructorName = function.Parent is RecordBinding record
            ? record.ManagedName
            : NormalizeEnumManagedTypeName(function.ManagedName);
        var importMethodName = GetManagedImportMethodName(function);

        writer.Write($$"""
            public {{constructorName}}({{parameterList}})
                : this({{importMethodName}}({{invokeArguments}}), true)
            {
            }
            """);
        return writer.ToString();
    }

