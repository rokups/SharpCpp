using SharpCpp.Model.Ast;
using SharpCpp.Model.Utilities;

namespace SharpCpp.Rendering;

public static class BindingOutputRenderer
{
    public static GeneratedBindingSet Render(BindingCompilation compilation, string fileStem)
    {
        ArgumentNullException.ThrowIfNull(compilation);
        ArgumentException.ThrowIfNullOrWhiteSpace(fileStem);

        var files = new[]
        {
            new GeneratedBindingFile($"{fileStem}.Bindings.g.cs", RenderManagedBindings(compilation)),
            new GeneratedBindingFile($"{fileStem}.Bindings.Aliases.g.cs", RenderAliasBindings()),
            new GeneratedBindingFile($"{fileStem}.Bindings.g.cpp", RenderNativeBindings(compilation))
        };

        return new GeneratedBindingSet(files);
    }

    private static string RenderManagedBindings(BindingCompilation compilation)
    {
        var writer = new CodeWriter();
        var records = compilation.Records.OrderBy(static record => record.ManagedName, StringComparer.Ordinal).ToArray();
        var functions = compilation.Functions.OrderBy(static function => function.ManagedName, StringComparer.Ordinal).ToArray();

        writer.Write(
            $$"""
            // <auto-generated />
            using System.Runtime.InteropServices;

            namespace {{compilation.ManagedNamespace}};
            """);

        foreach (var record in records)
        {
            writer.WriteLine();
            writer.Write(RenderRecord(compilation, record));
        }

        foreach (var @enum in compilation.Enums.OrderBy(static item => item.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write(RenderEnum(@enum));
        }

        writer.WriteLine();
        writer.Write(
            $$"""
            public static partial class {{compilation.ManagedClassName}}
            {
            """);

        foreach (var function in functions)
        {
            writer.WriteLine();
            writer.Write(RenderManagedWrapperMethod(function));
            writer.WriteLine();
            writer.Write(RenderManagedImportDeclaration(compilation, function));
        }

        writer.WriteLine();
        writer.Write(
            """
            }
            """);

        return writer.ToString();
    }

    private static string RenderManagedWrapperMethod(FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            function.Parameters.Select(RenderManagedParameter));
        var invokeArguments = string.Join(", ", function.Parameters.Select(RenderManagedInvocationArgument));
        var returnTypeName = GetManagedWrapperTypeName(function.ReturnType);

        writer.Write($$"""
            public static {{returnTypeName}} {{function.ManagedName}}({{parameterList}})
            {
            """);

        if (function.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
        {
            writer.Write($$"""
                __PInvoke_{{function.ManagedName}}({{invokeArguments}});
                """);
        }
        else if (function.ReturnType.Kind == BindingTypeKind.Handle)
        {
            writer.Write($$"""
                return new {{function.ReturnType.ManagedTypeName}}(__PInvoke_{{function.ManagedName}}({{invokeArguments}}));
                """);
        }
        else
        {
            writer.Write($$"""
                return __PInvoke_{{function.ManagedName}}({{invokeArguments}});
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static string RenderManagedImportDeclaration(BindingCompilation compilation, FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            function.Parameters.Select(RenderManagedParameter));
        var returnTypeName = GetManagedImportTypeName(function.ReturnType);
        var returnAttribute = GetManagedReturnAttribute(function.ReturnType);

        writer.Write(
            $$"""
            [LibraryImport("{{compilation.NativeLibraryName}}", EntryPoint = "{{function.EntryPointName}}")]
            {{returnAttribute}}
            private static partial {{returnTypeName}} __PInvoke_{{function.ManagedName}}({{parameterList}});
            """);
        return writer.ToString();
    }

    private static string RenderAliasBindings()
    {
        return "// <auto-generated />\n// No alias glue is required for this bootstrap pipeline.\n";
    }

    private static string RenderRecord(BindingCompilation compilation, RecordBinding record)
    {
        var writer = new CodeWriter();
        writer.Write(
            $$"""
            public sealed partial class {{record.ManagedName}}
            {
            internal {{record.ManagedName}}(nint handle)
            {
            Handle = handle;
            }

            public nint Handle { get; }

            public bool IsNull => Handle == 0;
            """);

        foreach (var method in record.Members.OfType<FunctionBinding>().OrderBy(static method => method.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write(RenderManagedInstanceMethod(method));
            writer.WriteLine();
            writer.Write(RenderManagedInstanceImportDeclaration(compilation, method));
        }

        foreach (var field in record.Members.OfType<FieldBinding>().OrderBy(static field => field.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write(RenderManagedProperty(field));
            writer.WriteLine();
            writer.Write(RenderManagedFieldGetterImportDeclaration(compilation, field));

            if (!field.IsReadOnly)
            {
                writer.WriteLine();
                writer.Write(RenderManagedFieldSetterImportDeclaration(compilation, field));
            }
        }

        writer.WriteLine();
        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static string RenderManagedInstanceMethod(FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            function.Parameters.Select(RenderManagedParameter));
        var invokeArguments = string.Join(", ", new[] { "Handle" }.Concat(function.Parameters.Select(RenderManagedInvocationArgument)));
        var returnTypeName = GetManagedWrapperTypeName(function.ReturnType);

        writer.Write($$"""
            public {{returnTypeName}} {{function.ManagedName}}({{parameterList}})
            {
            """);

        if (function.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
        {
            writer.Write($$"""
                __PInvoke_{{function.ManagedName}}({{invokeArguments}});
                """);
        }
        else if (function.ReturnType.Kind == BindingTypeKind.Handle)
        {
            writer.Write($$"""
                return new {{function.ReturnType.ManagedTypeName}}(__PInvoke_{{function.ManagedName}}({{invokeArguments}}));
                """);
        }
        else
        {
            writer.Write($$"""
                return __PInvoke_{{function.ManagedName}}({{invokeArguments}});
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static string RenderManagedInstanceImportDeclaration(BindingCompilation compilation, FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            new[] { "nint self" }.Concat(function.Parameters.Select(RenderManagedParameter)));
        var returnTypeName = GetManagedImportTypeName(function.ReturnType);
        var returnAttribute = GetManagedReturnAttribute(function.ReturnType);

        writer.Write(
            $$"""
            [LibraryImport("{{compilation.NativeLibraryName}}", EntryPoint = "{{function.EntryPointName}}")]
            {{returnAttribute}}
            private static partial {{returnTypeName}} __PInvoke_{{function.ManagedName}}({{parameterList}});
            """);
        return writer.ToString();
    }

    private static string RenderEnum(EnumBinding @enum)
    {
        var writer = new CodeWriter();

        if (@enum.IsFlags)
        {
            writer.Write("[Flags]");
        }

        writer.Write($$"""
            public enum {{@enum.ManagedName}} : {{GetManagedEnumUnderlyingTypeName(@enum)}}
            {
            """);

        foreach (var value in @enum.Values)
        {
            writer.Write($$"""
                {{value.ManagedName}} = {{value.ValueExpression}},
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static string RenderManagedProperty(FieldBinding field)
    {
        var writer = new CodeWriter();
        var propertyTypeName = GetManagedWrapperTypeName(field.Type);
        writer.Write($$"""
            public {{propertyTypeName}} {{field.ManagedName}}
            {
            get
            {
            """);

        if (field.Type.Kind == BindingTypeKind.Handle)
        {
            writer.Write($$"""
                return new {{field.Type.ManagedTypeName}}(__PInvoke_Get_{{field.ManagedName}}(Handle));
                """);
        }
        else
        {
            writer.Write($$"""
                return __PInvoke_Get_{{field.ManagedName}}(Handle);
                """);
        }

        writer.Write(
            """
            }
            """);

        if (!field.IsReadOnly)
        {
            writer.Write($$"""
                set
                {
                __PInvoke_Set_{{field.ManagedName}}(Handle, value);
                }
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static string RenderManagedFieldGetterImportDeclaration(BindingCompilation compilation, FieldBinding field)
    {
        var writer = new CodeWriter();
        var returnTypeName = GetManagedImportTypeName(field.Type);
        var returnAttribute = GetManagedReturnAttribute(field.Type);

        writer.Write($$"""
            [LibraryImport("{{compilation.NativeLibraryName}}", EntryPoint = "sharpcpp_e2e_{{field.OwningRecordCppTypeName}}_{{field.NativeName}}_get")]
            {{returnAttribute}}
            private static partial {{returnTypeName}} __PInvoke_Get_{{field.ManagedName}}(nint self);
            """);
        return writer.ToString();
    }

    private static string RenderManagedFieldSetterImportDeclaration(BindingCompilation compilation, FieldBinding field)
    {
        var writer = new CodeWriter();
        var parameter = RenderManagedParameter(
            new ParameterBinding(
                $"field:set:{field.NativeName}",
                "value",
                "value",
                field.Type,
                BindingParameterDirection.In,
                BindingParameterAbiKind.Value,
                field.CppTypeName));

        writer.Write($$"""
            [LibraryImport("{{compilation.NativeLibraryName}}", EntryPoint = "sharpcpp_e2e_{{field.OwningRecordCppTypeName}}_{{field.NativeName}}_set")]
            private static partial void __PInvoke_Set_{{field.ManagedName}}(nint self, {{parameter}});
            """);
        return writer.ToString();
    }

    private static string RenderNativeBindings(BindingCompilation compilation)
    {
        var writer = new CodeWriter();
        var functions = compilation.Functions.OrderBy(static function => function.ManagedName, StringComparer.Ordinal).ToArray();

        writer.Write(
            """
            // <auto-generated />
            #include "SharpCpp/Marshaller.hpp"
            #if defined(_WIN32)
            #define SHARPCPP_EXPORT extern "C" __declspec(dllexport)
            #else
            #define SHARPCPP_EXPORT extern "C" __attribute__((visibility("default")))
            #endif

            using namespace SharpCpp;
            """);

        foreach (var headerFile in compilation.HeaderFiles.OrderBy(static header => header, StringComparer.Ordinal))
        {
            writer.Write($$"""

                #include "{{headerFile}}"
                """);
        }

        foreach (var function in functions)
        {
            if (!function.IsStatic && function.Parent is RecordBinding)
            {
                continue;
            }

            var parameterList = string.Join(
                ", ",
                function.Parameters.Select(RenderNativeParameter));
            var invokeArguments = string.Join(", ", function.Parameters.Select(RenderNativeInvocationArgument));

            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT ret_t<{{function.CppReturnTypeName}}> {{function.EntryPointName}}({{parameterList}})
                {
                """);

            if (function.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
            {
                writer.Write($$"""
                    {{function.NativeName}}({{invokeArguments}});
                    """);
            }
            else
            {
                writer.Write($$"""
                    return {{function.NativeName}}({{invokeArguments}});
                    """);
            }

            writer.Write($$"""
                }
                """);
        }

        foreach (var method in compilation.Records.SelectMany(static record => record.Members.OfType<FunctionBinding>()).OrderBy(static method => method.ManagedName, StringComparer.Ordinal))
        {
            var parameterList = string.Join(
                ", ",
                new[] { $"arg_t<{method.OwningRecordCppTypeName}*> self" }.Concat(method.Parameters.Select(RenderNativeParameter)));
            var invokeArguments = string.Join(", ", method.Parameters.Select(RenderNativeInvocationArgument));

            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT ret_t<{{method.CppReturnTypeName}}> {{method.EntryPointName}}({{parameterList}})
                {
                """);

            if (method.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
            {
                writer.Write($$"""
                    reinterpret_cast<{{method.OwningRecordCppTypeName}}*>(self)->{{method.NativeName}}({{invokeArguments}});
                    """);
            }
            else
            {
                writer.Write($$"""
                    return reinterpret_cast<{{method.OwningRecordCppTypeName}}*>(self)->{{method.NativeName}}({{invokeArguments}});
                    """);
            }

            writer.Write($$"""
                }
                """);
        }

        foreach (var field in compilation.Records.SelectMany(static record => record.Members.OfType<FieldBinding>()).OrderBy(static field => field.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT ret_t<{{field.CppTypeName}}> sharpcpp_e2e_{{field.OwningRecordCppTypeName}}_{{field.NativeName}}_get(arg_t<{{field.OwningRecordCppTypeName}}*> self)
                {
                return reinterpret_cast<{{field.OwningRecordCppTypeName}}*>(self)->{{field.NativeName}};
                }
                """);

            if (!field.IsReadOnly)
            {
                writer.WriteLine();
                writer.Write($$"""
                    SHARPCPP_EXPORT ret_t<void> sharpcpp_e2e_{{field.OwningRecordCppTypeName}}_{{field.NativeName}}_set(arg_t<{{field.OwningRecordCppTypeName}}*> self, arg_t<{{field.CppTypeName}}> value)
                    {
                    reinterpret_cast<{{field.OwningRecordCppTypeName}}*>(self)->{{field.NativeName}} = value;
                    }
                    """);
            }
        }

        return writer.ToString();
    }

    private static string GetManagedWrapperTypeName(BindingType type)
    {
        return type.Kind switch
        {
            BindingTypeKind.Primitive => type.ManagedTypeName,
            BindingTypeKind.Handle => type.ManagedTypeName,
            BindingTypeKind.Enum => NormalizeEnumManagedTypeName(type.ManagedTypeName),
            _ => throw new NotSupportedException($"Managed wrapper emission does not support '{type.Kind}'.")
        };
    }

    private static string GetManagedImportTypeName(BindingType type)
    {
        return type.Kind switch
        {
            BindingTypeKind.Primitive => type.ManagedTypeName,
            BindingTypeKind.Handle => "nint",
            BindingTypeKind.Enum => NormalizeEnumManagedTypeName(type.ManagedTypeName),
            _ => throw new NotSupportedException($"Managed import emission does not support '{type.Kind}'.")
        };
    }

    private static string GetNativeAbiTypeName(BindingType type)
    {
        return type.Kind switch
        {
            BindingTypeKind.Primitive => type.AbiTypeName,
            BindingTypeKind.Handle => type.AbiTypeName,
            _ => throw new NotSupportedException($"Native emission does not support '{type.Kind}'.")
        };
    }

    private static string RenderManagedParameter(ParameterBinding parameter)
    {
        var modifier = parameter.Direction switch
        {
            BindingParameterDirection.In when parameter.AbiKind != BindingParameterAbiKind.Value => "in ",
            BindingParameterDirection.Ref => "ref ",
            BindingParameterDirection.Out => "out ",
            _ => string.Empty
        };
        var attribute = GetManagedParameterAttribute(parameter.Type);

        return $"{attribute}{modifier}{GetManagedImportTypeName(parameter.Type)} {parameter.ManagedName}";
    }

    private static string RenderNativeParameter(ParameterBinding parameter)
    {
        return $"arg_t<{parameter.CppTypeName}> {parameter.NativeName}";
    }

    private static string RenderNativeInvocationArgument(ParameterBinding parameter)
    {
        return parameter.AbiKind switch
        {
            BindingParameterAbiKind.Value => parameter.NativeName,
            BindingParameterAbiKind.Reference => $"*{parameter.NativeName}",
            BindingParameterAbiKind.Pointer => parameter.NativeName,
            _ => throw new NotSupportedException($"Native invocation emission does not support abi kind '{parameter.AbiKind}'.")
        };
    }

    private static string RenderManagedInvocationArgument(ParameterBinding parameter)
    {
        return parameter.Direction switch
        {
            BindingParameterDirection.In when parameter.AbiKind != BindingParameterAbiKind.Value => $"in {parameter.ManagedName}",
            BindingParameterDirection.Ref => $"ref {parameter.ManagedName}",
            BindingParameterDirection.Out => $"out {parameter.ManagedName}",
            _ => parameter.ManagedName
        };
    }

    private static string GetManagedParameterAttribute(BindingType type)
    {
        return type.PrimitiveKind == BindingPrimitiveKind.Boolean
            ? "[MarshalAs(UnmanagedType.I1)] "
            : string.Empty;
    }

    private static string GetManagedReturnAttribute(BindingType type)
    {
        return type.PrimitiveKind == BindingPrimitiveKind.Boolean
            ? "[return: MarshalAs(UnmanagedType.I1)]"
            : string.Empty;
    }

    private static string GetManagedEnumUnderlyingTypeName(EnumBinding @enum)
    {
        return @enum.UnderlyingTypeName switch
        {
            "unsigned int" => "uint",
            "unsigned short" => "ushort",
            "unsigned long long" => "ulong",
            "int" => "int",
            "short" => "short",
            "long long" => "long",
            _ => "int"
        };
    }

    private static string NormalizeEnumManagedTypeName(string managedTypeName)
    {
        var normalized = managedTypeName
            .Replace("Const ", string.Empty, StringComparison.Ordinal)
            .Replace("const ", string.Empty, StringComparison.Ordinal)
            .Trim();

        if (!normalized.Contains(' ', StringComparison.Ordinal) && !normalized.Contains('_', StringComparison.Ordinal))
        {
            return normalized;
        }

        return string.Concat(
            normalized
                .Split([' ', '_'], StringSplitOptions.RemoveEmptyEntries)
                .Select(static part => char.ToUpperInvariant(part[0]) + part[1..]));
    }
}
