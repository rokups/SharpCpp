using SharpCpp.Model.Ast;
using SharpCpp.Model.Utilities;

namespace SharpCpp.Rendering;

public static class BindingOutputRenderer
{
    public static GeneratedBindingSet Render(BindingCompilation compilation, string fileStem)
    {
        ArgumentNullException.ThrowIfNull(compilation);
        ArgumentException.ThrowIfNullOrWhiteSpace(fileStem);

        var files = new[]
        {
            new GeneratedBindingFile($"{fileStem}.Bindings.g.cs", RenderManagedBindings(compilation)),
            new GeneratedBindingFile($"{fileStem}.Bindings.Aliases.g.cs", RenderAliasBindings()),
            new GeneratedBindingFile($"{fileStem}.Bindings.g.cpp", RenderNativeBindings(compilation))
        };

        return new GeneratedBindingSet(files);
    }

    private static string RenderManagedBindings(BindingCompilation compilation)
    {
        var writer = new CodeWriter();
        var records = compilation.Records.OrderBy(static record => record.ManagedName, StringComparer.Ordinal).ToArray();
        var functions = compilation.Functions.OrderBy(static function => function.ManagedName, StringComparer.Ordinal).ToArray();

        writer.Write(
            $$"""
            // <auto-generated />
            using System.Runtime.InteropServices;

            namespace {{compilation.ManagedNamespace}};
            """);

        foreach (var record in records)
        {
            writer.WriteLine();
            writer.Write(
                $$"""
                public sealed partial class {{record.ManagedName}}
                {
                internal {{record.ManagedName}}(nint handle)
                {
                Handle = handle;
                }

                public nint Handle { get; }

                public bool IsNull => Handle == 0;
                }
                """);
        }

        writer.WriteLine();
        writer.Write(
            $$"""
            public static partial class {{compilation.ManagedClassName}}
            {
            """);

        foreach (var function in functions)
        {
            writer.WriteLine();
            writer.Write(RenderManagedWrapperMethod(function));
            writer.WriteLine();
            writer.Write(RenderManagedImportDeclaration(compilation, function));
        }

        writer.WriteLine();
        writer.Write(
            """
            }
            """);

        return writer.ToString();
    }

    private static string RenderManagedWrapperMethod(FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            function.Parameters.Select(RenderManagedParameter));
        var invokeArguments = string.Join(", ", function.Parameters.Select(RenderManagedInvocationArgument));
        var returnTypeName = GetManagedWrapperTypeName(function.ReturnType);

        writer.Write($$"""
            public static {{returnTypeName}} {{function.ManagedName}}({{parameterList}})
            {
            """);

        if (function.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
        {
            writer.Write($$"""
                __PInvoke_{{function.ManagedName}}({{invokeArguments}});
                """);
        }
        else if (function.ReturnType.Kind == BindingTypeKind.Handle)
        {
            writer.Write($$"""
                return new {{function.ReturnType.ManagedTypeName}}(__PInvoke_{{function.ManagedName}}({{invokeArguments}}));
                """);
        }
        else
        {
            writer.Write($$"""
                return __PInvoke_{{function.ManagedName}}({{invokeArguments}});
                """);
        }

        writer.Write(
            """
            }
            """);
        return writer.ToString();
    }

    private static string RenderManagedImportDeclaration(BindingCompilation compilation, FunctionBinding function)
    {
        var writer = new CodeWriter();
        var parameterList = string.Join(
            ", ",
            function.Parameters.Select(RenderManagedParameter));
        var returnTypeName = GetManagedImportTypeName(function.ReturnType);
        var returnAttribute = GetManagedReturnAttribute(function.ReturnType);

        writer.Write(
            $$"""
            [LibraryImport("{{compilation.NativeLibraryName}}", EntryPoint = "{{function.EntryPointName}}")]
            {{returnAttribute}}
            private static partial {{returnTypeName}} __PInvoke_{{function.ManagedName}}({{parameterList}});
            """);
        return writer.ToString();
    }

    private static string RenderAliasBindings()
    {
        return "// <auto-generated />\n// No alias glue is required for this bootstrap pipeline.\n";
    }

    private static string RenderNativeBindings(BindingCompilation compilation)
    {
        var writer = new CodeWriter();
        var functions = compilation.Functions.OrderBy(static function => function.ManagedName, StringComparer.Ordinal).ToArray();

        writer.Write(
            """
            // <auto-generated />
            #if defined(_WIN32)
            #define SHARPCPP_EXPORT extern "C" __declspec(dllexport)
            #else
            #define SHARPCPP_EXPORT extern "C" __attribute__((visibility("default")))
            #endif
            """);

        foreach (var headerFile in compilation.HeaderFiles.OrderBy(static header => header, StringComparer.Ordinal))
        {
            writer.Write($$"""

                #include "{{headerFile}}"
                """);
        }

        foreach (var function in functions)
        {
            var parameterList = string.Join(
                ", ",
                function.Parameters.Select(RenderNativeParameter));
            var invokeArguments = string.Join(", ", function.Parameters.Select(RenderNativeInvocationArgument));

            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT {{GetNativeAbiTypeName(function.ReturnType)}} {{function.EntryPointName}}({{parameterList}})
                {
                """);

            if (function.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
            {
                writer.Write($$"""
                    {{function.NativeName}}({{invokeArguments}});
                    """);
            }
            else
            {
                writer.Write($$"""
                    return {{function.NativeName}}({{invokeArguments}});
                    """);
            }

            writer.Write($$"""
                }
                """);
        }

        return writer.ToString();
    }

    private static string GetManagedWrapperTypeName(BindingType type)
    {
        return type.Kind switch
        {
            BindingTypeKind.Primitive => type.ManagedTypeName,
            BindingTypeKind.Handle => type.ManagedTypeName,
            _ => throw new NotSupportedException($"Managed wrapper emission does not support '{type.Kind}'.")
        };
    }

    private static string GetManagedImportTypeName(BindingType type)
    {
        return type.Kind switch
        {
            BindingTypeKind.Primitive => type.ManagedTypeName,
            BindingTypeKind.Handle => "nint",
            _ => throw new NotSupportedException($"Managed import emission does not support '{type.Kind}'.")
        };
    }

    private static string GetNativeAbiTypeName(BindingType type)
    {
        return type.Kind switch
        {
            BindingTypeKind.Primitive => type.AbiTypeName,
            BindingTypeKind.Handle => type.AbiTypeName,
            _ => throw new NotSupportedException($"Native emission does not support '{type.Kind}'.")
        };
    }

    private static string RenderManagedParameter(ParameterBinding parameter)
    {
        var modifier = parameter.Direction switch
        {
            BindingParameterDirection.In when parameter.AbiKind != BindingParameterAbiKind.Value => "in ",
            BindingParameterDirection.Ref => "ref ",
            BindingParameterDirection.Out => "out ",
            _ => string.Empty
        };
        var attribute = GetManagedParameterAttribute(parameter.Type);

        return $"{attribute}{modifier}{GetManagedImportTypeName(parameter.Type)} {parameter.ManagedName}";
    }

    private static string RenderNativeParameter(ParameterBinding parameter)
    {
        var typeName = parameter.AbiKind switch
        {
            BindingParameterAbiKind.Value => GetNativeAbiTypeName(parameter.Type),
            BindingParameterAbiKind.Reference when parameter.Direction == BindingParameterDirection.In => $"const {GetNativeAbiTypeName(parameter.Type)}*",
            BindingParameterAbiKind.Reference => $"{GetNativeAbiTypeName(parameter.Type)}*",
            BindingParameterAbiKind.Pointer when parameter.Direction == BindingParameterDirection.In => $"const {GetNativeAbiTypeName(parameter.Type)}*",
            BindingParameterAbiKind.Pointer => $"{GetNativeAbiTypeName(parameter.Type)}*",
            _ => throw new NotSupportedException($"Native parameter emission does not support abi kind '{parameter.AbiKind}'.")
        };

        return $"{typeName} {parameter.NativeName}";
    }

    private static string RenderNativeInvocationArgument(ParameterBinding parameter)
    {
        return parameter.AbiKind switch
        {
            BindingParameterAbiKind.Value => parameter.NativeName,
            BindingParameterAbiKind.Reference => $"*{parameter.NativeName}",
            BindingParameterAbiKind.Pointer => parameter.NativeName,
            _ => throw new NotSupportedException($"Native invocation emission does not support abi kind '{parameter.AbiKind}'.")
        };
    }

    private static string RenderManagedInvocationArgument(ParameterBinding parameter)
    {
        return parameter.Direction switch
        {
            BindingParameterDirection.In when parameter.AbiKind != BindingParameterAbiKind.Value => $"in {parameter.ManagedName}",
            BindingParameterDirection.Ref => $"ref {parameter.ManagedName}",
            BindingParameterDirection.Out => $"out {parameter.ManagedName}",
            _ => parameter.ManagedName
        };
    }

    private static string GetManagedParameterAttribute(BindingType type)
    {
        return type.PrimitiveKind == BindingPrimitiveKind.Boolean
            ? "[MarshalAs(UnmanagedType.I1)] "
            : string.Empty;
    }

    private static string GetManagedReturnAttribute(BindingType type)
    {
        return type.PrimitiveKind == BindingPrimitiveKind.Boolean
            ? "[return: MarshalAs(UnmanagedType.I1)]"
            : string.Empty;
    }
}
