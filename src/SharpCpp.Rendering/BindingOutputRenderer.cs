    private static string RenderManagedFieldSetterImportDeclaration(BindingCompilation compilation, FieldBinding field)
    {
        var writer = new CodeWriter();
        var parameter = RenderManagedParameter(
            new ParameterBinding(
                $"field:set:{field.NativeName}",
                "value",
                "value",
                field.Type,
                BindingParameterDirection.In,
                BindingParameterAbiKind.Value,
                field.CppTypeName));

        writer.Write($$"""
            [LibraryImport("{{compilation.NativeLibraryName}}", EntryPoint = "sharpcpp_e2e_{{SanitizeNativeEntrypointName(field.OwningRecordCppTypeName)}}_{{field.NativeName}}_set")]
            private static partial void __PInvoke_Set_{{field.ManagedName}}(nint self, {{parameter}});
            """);
        return writer.ToString();
    }

    private static string RenderNativeBindings(BindingCompilation compilation)
    {
        var writer = new CodeWriter();
        var functions = compilation.Functions.OrderBy(static function => function.ManagedName, StringComparer.Ordinal).ToArray();

        writer.Write(
            """
            // <auto-generated />
            #include "SharpCpp/Marshaller.hpp"
            #include "SharpCpp/detail/MarshallerSupport.hpp"
            #if defined(_WIN32)
            #define SHARPCPP_EXPORT extern "C" __declspec(dllexport)
            #else
            #define SHARPCPP_EXPORT extern "C" __attribute__((visibility("default")))
            #endif

            using namespace SharpCpp;
            """);

        foreach (var headerFile in compilation.HeaderFiles.OrderBy(static header => header, StringComparer.Ordinal))
        {
            writer.Write($$"""

                #include "{{headerFile}}"
                """);
        }

        foreach (var function in functions)
        {
            if (function.Parent is RecordBinding || function.IsConstructor)
            {
                continue;
            }

            var parameterList = string.Join(", ", function.Parameters.Select(RenderNativeParameter));
            var abiArguments = string.Join(", ", function.Parameters.Select(static p => p.NativeName));
            var signature = BuildNativeFunctionSignature(function);

            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT ret_t<{{function.CppReturnTypeName}}> {{function.EntryPointName}}({{parameterList}})
                {
                using FT = {{signature}};
                """);

            if (function.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
            {
                writer.Write($$"""
                    MarshallerInvoker::invoke_as<FT>(static_cast<FT*>(&{{function.NativeName}}){{(abiArguments.Length > 0 ? $", {abiArguments}" : string.Empty)}});
                    """);
            }
            else
            {
                writer.Write($$"""
                    return MarshallerInvoker::invoke_as<FT>(static_cast<FT*>(&{{function.NativeName}}){{(abiArguments.Length > 0 ? $", {abiArguments}" : string.Empty)}});
                    """);
            }

            writer.Write("""
                }
                """);
        }

        var overloadedMethodNames = compilation.Records
            .SelectMany(static record => record.Members.OfType<FunctionBinding>().Where(static f => !f.IsConstructor && !f.IsStatic))
            .GroupBy(static f => (f.Parent, f.NativeName))
            .Where(static g => g.Skip(1).Any())
            .Select(static g => g.Key)
            .ToHashSet();

        foreach (var method in compilation.Records.SelectMany(static record => record.Members.OfType<FunctionBinding>()).Where(static function => !function.IsConstructor && !function.IsStatic).OrderBy(static method => method.ManagedName, StringComparer.Ordinal))
        {
            var parameterList = string.Join(", ", new[] { $"arg_t<{method.OwningRecordCppTypeName}*> self" }.Concat(method.Parameters.Select(RenderNativeParameter)));
            var abiArguments = string.Join(", ", method.Parameters.Select(static p => p.NativeName));
            var memberSignature = BuildNativeMethodSignature(method);
            var isOverloaded = overloadedMethodNames.Contains((method.Parent, method.NativeName));
            var methodExpr = isOverloaded
                ? $"static_cast<FT>(&{method.OwningRecordCppTypeName}::{method.NativeName})"
                : $"&{method.OwningRecordCppTypeName}::{method.NativeName}";

            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT ret_t<{{method.CppReturnTypeName}}> {{method.EntryPointName}}({{parameterList}})
                {
                using FT = {{memberSignature}};
                """);

            if (method.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
            {
                writer.Write($$"""
                    MarshallerInvoker::invoke<FT>({{methodExpr}}, self{{(abiArguments.Length > 0 ? $", {abiArguments}" : string.Empty)}});
                    """);
            }
            else
            {
                writer.Write($$"""
                    return MarshallerInvoker::invoke<FT>({{methodExpr}}, self{{(abiArguments.Length > 0 ? $", {abiArguments}" : string.Empty)}});
                    """);
            }

            writer.Write("""
                }
                """);
        }

        foreach (var method in compilation.Records.SelectMany(static record => record.Members.OfType<FunctionBinding>()).Where(static function => function.IsStatic).OrderBy(static method => method.ManagedName, StringComparer.Ordinal))
        {
            var parameterList = string.Join(", ", method.Parameters.Select(RenderNativeParameter));
            var abiArguments = string.Join(", ", method.Parameters.Select(static p => p.NativeName));
            var signature = BuildNativeFunctionSignature(method);

            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT ret_t<{{method.CppReturnTypeName}}> {{method.EntryPointName}}({{parameterList}})
                {
                using FT = {{signature}};
                """);

            if (method.ReturnType.PrimitiveKind == BindingPrimitiveKind.Void)
            {
                writer.Write($$"""
                    MarshallerInvoker::invoke_as<FT>(static_cast<FT*>(&{{method.OwningRecordCppTypeName}}::{{method.NativeName}}){{(abiArguments.Length > 0 ? $", {abiArguments}" : string.Empty)}});
                    """);
            }
            else
            {
                writer.Write($$"""
                    return MarshallerInvoker::invoke_as<FT>(static_cast<FT*>(&{{method.OwningRecordCppTypeName}}::{{method.NativeName}}){{(abiArguments.Length > 0 ? $", {abiArguments}" : string.Empty)}});
                    """);
            }

            writer.Write("""
                }
                """);
        }

        foreach (var constructor in compilation.Records.SelectMany(static record => record.Members.OfType<FunctionBinding>()).Where(static function => function.IsConstructor).OrderBy(static function => function.ManagedName, StringComparer.Ordinal))
        {
            var parameterList = string.Join(", ", constructor.Parameters.Select(RenderNativeParameter));
            var abiArguments = string.Join(", ", constructor.Parameters.Select(static p => p.NativeName));
            var constructorArgTypes = string.Join(", ", constructor.Parameters.Select(static p => p.CppTypeName));

            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT ret_t<{{constructor.CppReturnTypeName}}> {{constructor.EntryPointName}}({{parameterList}})
                {
                return MarshallerInvoker::construct<{{constructor.OwningRecordCppTypeName}}{{(constructorArgTypes.Length > 0 ? $", {constructorArgTypes}" : string.Empty)}}>({{abiArguments}});
                }
                """);
        }

        foreach (var field in compilation.Records.SelectMany(static record => record.Members.OfType<FieldBinding>()).OrderBy(static field => field.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT ret_t<{{field.CppTypeName}}> sharpcpp_e2e_{{SanitizeNativeEntrypointName(field.OwningRecordCppTypeName)}}_{{field.NativeName}}_get(arg_t<{{field.OwningRecordCppTypeName}}*> self)
                {
                return MarshallerInvoker::get_field<{{field.CppTypeName}}>(&{{field.OwningRecordCppTypeName}}::{{field.NativeName}}, self);
                }
                """);

            if (!field.IsReadOnly)
            {
                writer.WriteLine();
                writer.Write($$"""
                    SHARPCPP_EXPORT ret_t<void> sharpcpp_e2e_{{SanitizeNativeEntrypointName(field.OwningRecordCppTypeName)}}_{{field.NativeName}}_set(arg_t<{{field.OwningRecordCppTypeName}}*> self, arg_t<{{field.CppTypeName}}> value)
                    {
                    MarshallerInvoker::set_field<{{field.CppTypeName}}>(&{{field.OwningRecordCppTypeName}}::{{field.NativeName}}, self, value);
                    }
                    """);
            }
        }

        foreach (var record in compilation.Records.OrderBy(static record => record.ManagedName, StringComparer.Ordinal))
        {
            writer.WriteLine();
            writer.Write($$"""
                SHARPCPP_EXPORT ret_t<void> sharpcpp_e2e_{{record.NativeName}}_delete(arg_t<{{record.CppQualifiedName}}*> self)
                {
                MarshallerInvoker::destroy<{{record.CppQualifiedName}}>(self);
                }
                """);
        }

        return writer.ToString();
    }

    private static string GetManagedWrapperTypeName(BindingType type)
    {
        return type.Kind switch
        {
            BindingTypeKind.Primitive => type.ManagedTypeName,
            BindingTypeKind.Handle => type.ManagedTypeName,
            BindingTypeKind.Enum => NormalizeEnumManagedTypeName(type.ManagedTypeName),
            _ => throw new NotSupportedException($"Managed wrapper emission does not support '{type.Kind}'.")
        };
    }

    private static string GetManagedPublicReturnTypeName(BindingType type)
    {
        return GetManagedWrapperTypeName(type);
    }

    private static string GetManagedImportTypeName(BindingType type)
    {
        return type.Kind switch
        {
            BindingTypeKind.Primitive => type.ManagedTypeName,
            BindingTypeKind.Handle => "nint",
            BindingTypeKind.Enum => NormalizeEnumManagedTypeName(type.ManagedTypeName),
            _ => throw new NotSupportedException($"Managed import emission does not support '{type.Kind}'.")
        };
    }

    private static string GetNativeAbiTypeName(BindingType type)
    {
        return type.Kind switch
        {
            BindingTypeKind.Primitive => type.AbiTypeName,
            BindingTypeKind.Handle => type.AbiTypeName,
            _ => throw new NotSupportedException($"Native emission does not support '{type.Kind}'.")
        };
    }

    private static string RenderManagedParameter(ParameterBinding parameter)
    {
        var modifier = parameter.Direction switch
        {
            BindingParameterDirection.In when parameter.AbiKind != BindingParameterAbiKind.Value => "in ",
            BindingParameterDirection.Ref => "ref ",
            BindingParameterDirection.Out => "out ",
            _ => string.Empty
        };
        var attribute = GetManagedParameterAttribute(parameter.Type);

        return $"{attribute}{modifier}{GetManagedImportTypeName(parameter.Type)} {parameter.ManagedName}";
    }

    private static string RenderManagedPublicParameter(ParameterBinding parameter)
    {
        var modifier = parameter.Direction switch
        {
            BindingParameterDirection.In when parameter.AbiKind != BindingParameterAbiKind.Value => "in ",
            BindingParameterDirection.Ref => "ref ",
            BindingParameterDirection.Out => "out ",
            _ => string.Empty
        };

        var signature = $"{modifier}{GetManagedWrapperTypeName(parameter.Type)} {parameter.ManagedName}";

        if (parameter.Direction == BindingParameterDirection.In &&
            parameter.AbiKind == BindingParameterAbiKind.Value &&
            parameter.ManagedDefaultValueExpression is { Length: > 0 } defaultValueExpression)
        {
            signature += $" = {defaultValueExpression}";
        }

        return signature;
    }

    private static string RenderNativeParameter(ParameterBinding parameter)
    {
        return $"arg_t<{parameter.CppTypeName}> {parameter.NativeName}";
    }

    private static string BuildNativeFunctionSignature(FunctionBinding function)
    {
        var returnTypeName = function.CppReturnTypeName;
        var parameterTypes = string.Join(", ", function.Parameters.Select(static p => p.CppTypeName));
        return $"{returnTypeName}({parameterTypes})";
    }

    private static string BuildNativeMethodSignature(FunctionBinding method)
    {
        var returnTypeName = method.CppReturnTypeName;
        var parameterTypes = string.Join(", ", method.Parameters.Select(static p => p.CppTypeName));
        var constQualifier = method.IsConstMethod ? " const" : string.Empty;
        return $"{returnTypeName}({method.OwningRecordCppTypeName}::*)({parameterTypes}){constQualifier}";
    }

    private static string BuildNativeFunctionSignatureWithSelf(FunctionBinding method)
    {
        var returnTypeName = method.CppReturnTypeName;
        var parameterTypes = string.Join(", ", method.Parameters.Select(static p => p.CppTypeName));
        return $"{returnTypeName}({parameterTypes})";
    }

    private static string RenderManagedInvocationArgument(ParameterBinding parameter)
    {
        var valueExpression = parameter.Type.Kind == BindingTypeKind.Handle
            ? $"{parameter.ManagedName} is null ? 0 : {parameter.ManagedName}.Handle"
            : parameter.ManagedName;

        return parameter.Direction switch
        {
            BindingParameterDirection.In when parameter.AbiKind != BindingParameterAbiKind.Value => $"in {valueExpression}",
            BindingParameterDirection.Ref => $"ref {valueExpression}",
            BindingParameterDirection.Out => $"out {valueExpression}",
            _ => valueExpression
        };
    }

    private static ManagedInvocationPlan BuildManagedInvocationPlan(IEnumerable<ParameterBinding> parameters)
    {
        var arguments = new List<string>();
        var preCallStatements = new List<string>();
        var postCallStatements = new List<string>();

        foreach (var parameter in parameters)
        {
            if (parameter.Type.Kind == BindingTypeKind.Handle && parameter.Direction is BindingParameterDirection.Ref or BindingParameterDirection.Out)
            {
                var abiVariableName = $"__abi_{parameter.ManagedName}";

                if (parameter.Direction == BindingParameterDirection.Ref)
                {
                    preCallStatements.Add($$"""
                        var {{abiVariableName}} = {{parameter.ManagedName}} is null ? 0 : {{parameter.ManagedName}}.Handle;
                        """);
                    arguments.Add($"ref {abiVariableName}");
                }
                else
                {
                    preCallStatements.Add($$"""
                        nint {{abiVariableName}};
                        """);
                    arguments.Add($"out {abiVariableName}");
                }

                postCallStatements.Add($$"""
                    {{parameter.ManagedName}} = new {{parameter.Type.ManagedTypeName}}({{abiVariableName}});
                    """);
                continue;
            }

            arguments.Add(RenderManagedInvocationArgument(parameter));
        }

        return new ManagedInvocationPlan(arguments, preCallStatements, postCallStatements);
    }

    private sealed record ManagedInvocationPlan(
        IReadOnlyList<string> Arguments,
        IReadOnlyList<string> PreCallStatements,
        IReadOnlyList<string> PostCallStatements);

    private sealed record AccessorProperty(string PropertyName, FunctionBinding? Getter, FunctionBinding? Setter);

    private static string GetManagedImportMethodName(FunctionBinding function)
    {
        var builder = new StringBuilder("__PInvoke_");
        builder.Append(function.ManagedName);

        foreach (var parameter in function.Parameters)
        {
            builder.Append('_');
            builder.Append(SanitizeManagedImportNamePart(parameter.CppTypeName));
        }

        return builder.ToString();
    }

    private static string SanitizeManagedImportNamePart(string value)
    {
        return value
            .Replace("const ", "Const_", StringComparison.Ordinal)
            .Replace("::", "_", StringComparison.Ordinal)
            .Replace("*", "Ptr", StringComparison.Ordinal)
            .Replace("&", "Ref", StringComparison.Ordinal)
            .Replace("<", "_", StringComparison.Ordinal)
            .Replace(">", "_", StringComparison.Ordinal)
            .Replace(",", "_", StringComparison.Ordinal)
            .Replace(" ", "_", StringComparison.Ordinal);
    }

    private static string SanitizeNativeEntrypointName(string value)
    {
        return value.Replace("::", "_", StringComparison.Ordinal);
    }

    private static string GetManagedParameterAttribute(BindingType type)
    {
        return type.PrimitiveKind == BindingPrimitiveKind.Boolean
            ? "[MarshalAs(UnmanagedType.I1)] "
            : string.Empty;
    }

    private static string GetManagedReturnAttribute(BindingType type)
    {
        return type.PrimitiveKind == BindingPrimitiveKind.Boolean
            ? "[return: MarshalAs(UnmanagedType.I1)]"
            : string.Empty;
    }

    private static string GetManagedEnumUnderlyingTypeName(EnumBinding @enum)
    {
        return @enum.UnderlyingTypeName switch
        {
            "unsigned int" => "uint",
            "unsigned short" => "ushort",
            "unsigned long long" => "ulong",
            "int" => "int",
            "short" => "short",
            "long long" => "long",
            _ => "int"
        };
    }

    private static string NormalizeEnumManagedTypeName(string managedTypeName)
    {
        var normalized = managedTypeName
            .Replace("Const ", string.Empty, StringComparison.Ordinal)
            .Replace("const ", string.Empty, StringComparison.Ordinal)
            .Trim();

        if (!normalized.Contains(' ', StringComparison.Ordinal) && !normalized.Contains('_', StringComparison.Ordinal))
        {
            return normalized;
        }

        return string.Concat(
            normalized
                .Split([' ', '_'], StringSplitOptions.RemoveEmptyEntries)
                .Select(static part => char.ToUpperInvariant(part[0]) + part[1..]));
    }
