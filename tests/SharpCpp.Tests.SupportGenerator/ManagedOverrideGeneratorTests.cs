using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using SharpCpp.Support.SourceGenerator;
using Xunit;

namespace SharpCpp.Tests.SupportGenerator;

/// <summary>Tests of the generator that emits IsManagedOverride for user overrides of generated virtual methods.</summary>
public sealed class ManagedOverrideGeneratorTests
{
    // A stand-in for the generated bindings: the attribute, NativeObject and two director classes.
    private const string Prelude = """
        namespace SharpCpp.Support
        {
            [System.AttributeUsage(System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
            public sealed class ManagedVirtualSlotAttribute : System.Attribute
            {
                public ManagedVirtualSlotAttribute(string key) { Key = key; }
                public string Key { get; }
            }

            public abstract class NativeObject
            {
                protected virtual bool IsManagedOverride(string slotKey) => false;
            }
        }

        namespace Lib
        {
            using SharpCpp.Support;

            public class Renderer : NativeObject
            {
                [ManagedVirtualSlot("Lib.Renderer.Render()")]
                public virtual void Render() { }

                [ManagedVirtualSlot("Lib.Renderer.Draw(int)")]
                public virtual void Draw(int value) { }

                [ManagedVirtualSlot("Lib.Renderer.Draw(string)")]
                public virtual void Draw(string value) { }

                [ManagedVirtualSlot("Lib.Renderer.Update()")]
                protected virtual void Update() { }

                public virtual void Plain() { }
            }

            public class Plane : NativeObject
            {
                public virtual int Left() => 0;
            }

            public class Counter : Plane
            {
                [ManagedVirtualSlot("Lib.Counter.Left()")]
                public override int Left() => 1;
            }
        }
        """;

    private static (ImmutableArray<GeneratedSourceResult> Sources, ImmutableArray<Diagnostic> GeneratorDiagnostics, ImmutableArray<Diagnostic> CompilationErrors)
        Run(string userSource)
    {
        var trustedAssemblies = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator);
        var references = trustedAssemblies.Select(path => MetadataReference.CreateFromFile(path)).ToArray();
        var compilation = CSharpCompilation.Create(
            "TestAssembly",
            new[] { CSharpSyntaxTree.ParseText(Prelude), CSharpSyntaxTree.ParseText(userSource) },
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));

        GeneratorDriver driver = CSharpGeneratorDriver.Create(new ManagedOverrideGenerator());
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var updated, out _);
        var result = driver.GetRunResult();
        var errors = updated.GetDiagnostics().Where(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToImmutableArray();
        return (result.Results[0].GeneratedSources, result.Results[0].Diagnostics, errors);
    }

    private static string Normalize(string text) => text.Replace("\r\n", "\n", StringComparison.Ordinal).Trim();

    [Fact]
    public void Override_of_a_slot_method_emits_IsManagedOverride()
    {
        var (sources, diagnostics, errors) = Run("""
            namespace App
            {
                public partial class MyRenderer : Lib.Renderer
                {
                    public override void Render() { }
                }
            }
            """);

        Assert.Empty(diagnostics);
        Assert.Empty(errors);
        var source = Assert.Single(sources);
        Assert.Equal("""
            // <auto-generated/>
            #nullable enable

            namespace App
            {
                partial class MyRenderer
                {
                    protected override bool IsManagedOverride(string slotKey) => slotKey switch
                    {
                        "Lib.Renderer.Render()" => true,
                        _ => base.IsManagedOverride(slotKey),
                    };
                }
            }
            """, Normalize(source.SourceText.ToString()));
    }

    [Fact]
    public void Overloads_are_distinguished_by_their_own_keys()
    {
        var (sources, diagnostics, errors) = Run("""
            public partial class OnlyInt : Lib.Renderer
            {
                public override void Draw(int value) { }
            }

            public partial class OnlyString : Lib.Renderer
            {
                public override void Draw(string value) { }
            }

            public partial class Both : Lib.Renderer
            {
                public override void Draw(int value) { }
                public override void Draw(string value) { }
            }
            """);

        Assert.Empty(diagnostics);
        Assert.Empty(errors);
        Assert.Equal(3, sources.Length);
        var onlyInt = SourceOf(sources, "OnlyInt");
        Assert.Contains("\"Lib.Renderer.Draw(int)\" => true", onlyInt);
        Assert.DoesNotContain("Draw(string)", onlyInt);
        var onlyString = SourceOf(sources, "OnlyString");
        Assert.Contains("\"Lib.Renderer.Draw(string)\" => true", onlyString);
        Assert.DoesNotContain("Draw(int)", onlyString);
        Assert.Contains("\"Lib.Renderer.Draw(int)\" or \"Lib.Renderer.Draw(string)\" => true", SourceOf(sources, "Both"));
    }

    [Fact]
    public void Two_level_hierarchy_emits_the_keys_of_each_level()
    {
        var (sources, diagnostics, errors) = Run("""
            public partial class Mid : Lib.Renderer
            {
                public override void Render() { }
            }

            public partial class Leaf : Mid
            {
                public override void Render() { }
                public sealed override void Draw(int value) { }
            }

            public partial class Last : Leaf
            {
                public override void Draw(string value) { }
            }
            """);

        Assert.Empty(diagnostics);
        Assert.Empty(errors);
        Assert.Equal(3, sources.Length);
        var mid = SourceOf(sources, "Mid");
        Assert.Contains("\"Lib.Renderer.Render()\" => true", mid);
        Assert.DoesNotContain("Draw", mid);
        Assert.Contains("\"Lib.Renderer.Draw(int)\" or \"Lib.Renderer.Render()\" => true", SourceOf(sources, "Leaf"));
        var last = SourceOf(sources, "Last");
        Assert.Contains("\"Lib.Renderer.Draw(string)\" => true", last);
        Assert.DoesNotContain("Render()", last);
    }

    [Fact]
    public void Attribute_on_an_intermediate_override_is_found()
    {
        var (sources, diagnostics, errors) = Run("""
            public partial class Custom : Lib.Counter
            {
                public override int Left() => 7;
            }
            """);

        Assert.Empty(diagnostics);
        Assert.Empty(errors);
        Assert.Contains("\"Lib.Counter.Left()\" => true", Assert.Single(sources).SourceText.ToString());
    }

    [Fact]
    public void Protected_virtual_override_is_found()
    {
        var (sources, diagnostics, errors) = Run("""
            public partial class Custom : Lib.Renderer
            {
                protected override void Update() { }
            }
            """);

        Assert.Empty(diagnostics);
        Assert.Empty(errors);
        Assert.Contains("\"Lib.Renderer.Update()\" => true", Assert.Single(sources).SourceText.ToString());
    }

    [Fact]
    public void Nested_generic_types_in_namespaces_keep_their_declaration_chain()
    {
        var (sources, diagnostics, errors) = Run("""
            namespace App.Deep
            {
                public partial class Outer<T>
                {
                    public partial struct Marker { }

                    public partial class Inner<U, V> : Lib.Renderer where U : class
                    {
                        public override void Render() { }
                    }
                }

                public partial class Outer<T>
                {
                    public partial class Inner<U, V> { }
                }
            }
            """);

        Assert.Empty(diagnostics);
        Assert.Empty(errors);
        var text = Normalize(Assert.Single(sources).SourceText.ToString());
        Assert.Contains("namespace App.Deep", text);
        Assert.Contains("partial class Outer<T>", text);
        Assert.Contains("partial class Inner<U, V>", text);
    }

    [Fact]
    public void Hint_names_are_unique_for_types_with_equal_names()
    {
        var (sources, diagnostics, errors) = Run("""
            public partial class Same : Lib.Renderer { public override void Render() { } }
            namespace Other { public partial class Same : Lib.Renderer { public override void Render() { } } }
            public partial class Gen<T> : Lib.Renderer { public override void Render() { } }
            public partial class Gen<T1, T2> : Lib.Renderer { public override void Render() { } }
            """);

        Assert.Empty(diagnostics);
        Assert.Empty(errors);
        Assert.Equal(4, sources.Length);
        Assert.Equal(4, sources.Select(static source => source.HintName).Distinct().Count());
    }

    [Fact]
    public void Non_partial_class_reports_an_error()
    {
        var (sources, diagnostics, _) = Run("""
            public class NotPartial : Lib.Renderer
            {
                public override void Render() { }
            }
            """);

        Assert.Empty(sources);
        var diagnostic = Assert.Single(diagnostics);
        Assert.Equal("SCPPSG001", diagnostic.Id);
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
        Assert.Contains("'NotPartial'", diagnostic.GetMessage());
    }

    [Fact]
    public void Non_partial_containing_type_reports_an_error()
    {
        var (sources, diagnostics, _) = Run("""
            public class Holder
            {
                public partial class Nested : Lib.Renderer
                {
                    public override void Render() { }
                }
            }
            """);

        Assert.Empty(sources);
        var diagnostic = Assert.Single(diagnostics);
        Assert.Equal("SCPPSG001", diagnostic.Id);
        Assert.Contains("mark 'Holder' partial", diagnostic.GetMessage());
    }

    [Fact]
    public void Class_without_slot_overrides_gets_no_output()
    {
        var (sources, diagnostics, errors) = Run("""
            public partial class NoOverrides : Lib.Renderer
            {
                public void Helper() { }
            }

            public partial class PlainOverride : Lib.Renderer
            {
                public override void Plain() { }
                public override string ToString() => "x";
            }

            public class NotPartialWithoutSlots : Lib.Renderer
            {
                public override void Plain() { }
            }
            """);

        Assert.Empty(sources);
        Assert.Empty(diagnostics);
        Assert.Empty(errors);
    }

    [Fact]
    public void Partial_type_with_several_parts_emits_once()
    {
        var (sources, diagnostics, errors) = Run("""
            public partial class Split : Lib.Renderer
            {
                public override void Render() { }
            }

            public partial class Split
            {
                public override void Draw(int value) { }
            }
            """);

        Assert.Empty(diagnostics);
        Assert.Empty(errors);
        var source = Assert.Single(sources).SourceText.ToString();
        Assert.Contains("\"Lib.Renderer.Draw(int)\" or \"Lib.Renderer.Render()\" => true", source);
    }

    private static string SourceOf(ImmutableArray<GeneratedSourceResult> sources, string typeName) =>
        sources.Single(source => source.HintName.StartsWith(typeName + ".", StringComparison.Ordinal)).SourceText.ToString();
}
